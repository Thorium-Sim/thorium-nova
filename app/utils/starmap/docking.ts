import { getShipSystems } from "@thorium/utils/.server/ship/getShipSystem";
import { Entity } from "@thorium/utils/ecs";
import { Quaternion, Vector3 } from "three";

type Coordinate = { x: number; y: number; z: number };

const worldPortPos = new Vector3();
const hostPosVec = new Vector3();
const worldHostDir = new Vector3();
const localGuestDir = new Vector3();
const startRotation = new Quaternion();
const guestRotation = new Quaternion();
const guestPortPosVec = new Vector3();
/**
 * Figure out the rotation and position of a guest ship when it is docked with another ship.
 * Using vectors for the port directions means we have a single degree of rotational freedom.
 * That shouldn't matter too much, and supplying the current guest rotation makes it so the
 * final rotation is as close to the current rotation of the ship as possible.
 *
 * Note: This function was generated by Claude, but reviewed by hand.
 */
export function computeDockedTransform({
	hostPosition,
	hostRotation,
	hostPortPos,
	hostPortDir,
	hostScale,
	guestPortPos,
	guestPortDir,
	guestScale,
	currentGuestRotation = null,
}: {
	hostPosition: Coordinate;
	hostRotation: Coordinate & { w: number };
	hostPortPos: Coordinate;
	hostPortDir: [number, number, number];
	hostScale: number;
	guestPortPos: Coordinate;
	guestPortDir: [number, number, number];
	guestScale: number;
	currentGuestRotation?: (Coordinate & { w: number }) | null;
}) {
	// --- 1. Host port, in world space ---------------------------------------
	worldPortPos
		.set(hostPortPos.x, hostPortPos.y, hostPortPos.z)
		.multiplyScalar(hostScale)
		.applyQuaternion(hostRotation)
		.add(hostPosVec.set(hostPosition.x, hostPosition.y, hostPosition.z));

	worldHostDir
		.set(...hostPortDir)
		.applyQuaternion(hostRotation)
		.normalize();

	// Ports face each other -> guest's outward direction must be the negation
	const targetGuestDir = worldHostDir.clone().negate();
	localGuestDir.set(...guestPortDir).normalize();

	// --- 2. Solve for guest rotation -----------------------------------------

	// No key vectors given -> minimal rotation. This rotates the guest ship
	// the *least* amount needed to line up the port direction, preserving
	// whatever roll it already had. Good default for axially-symmetric
	// ports, and avoids a visual "twist snap" during an approach animation.
	if (currentGuestRotation) {
		startRotation.set(
			currentGuestRotation.x,
			currentGuestRotation.y,
			currentGuestRotation.z,
			currentGuestRotation.w,
		);
	} else {
		startRotation.identity();
	}
	const currentWorldDir = localGuestDir.clone().applyQuaternion(startRotation);

	guestRotation.setFromUnitVectors(currentWorldDir, targetGuestDir).multiply(startRotation);

	// --- 3. Solve for guest position ------------------------------------------
	// Place the guest ship so that ITS port (offset + rotated) lands exactly
	// on the host's port position.
	const guestPosition = worldPortPos
		.clone()
		.sub(
			guestPortPosVec
				.set(guestPortPos.x, guestPortPos.y, guestPortPos.z)
				.multiplyScalar(guestScale)
				.applyQuaternion(guestRotation),
		);

	return { position: guestPosition, rotation: guestRotation };
}

const anchorA = new Vector3();
const anchorB = new Vector3();
const frameA = new Quaternion();
const frameB = new Quaternion();
const forward = new Vector3(0, 0, 1);

export function dockEntities(guest: Entity, host: Entity) {
	const ecs = guest.ecs;
	const [hostPort] = getShipSystems(ecs, { systemType: "dockingPort", shipId: host.id });
	const [guestPort] = getShipSystems(ecs, { systemType: "dockingPort", shipId: guest.id });
	if (!hostPort.components.position || !guestPort.components.position)
		throw new Error("Unable to dock — missing position component.");

	const jointEntity = new Entity();
	jointEntity.addComponent("fixedJoint", {
		idA: host?.id,
		idB: guest?.id,
		anchorA: {
			...anchorA
				.set(
					hostPort.components.position.x,
					hostPort.components.position.y,
					hostPort.components.position.z,
				)
				.divideScalar(1000),
		},
		anchorB: {
			...anchorB
				.set(
					guestPort.components.position.x,
					guestPort.components.position.y,
					guestPort.components.position.z,
				)
				.divideScalar(1000),
		},
		frameA: {
			...frameA.setFromUnitVectors(forward, hostPort.components.isDockingPort!.orientation),
		},
		frameB: {
			...frameB.setFromUnitVectors(forward, guestPort.components.isDockingPort!.orientation),
		},
	});

	ecs.addEntity(jointEntity);

	guest?.addComponent("isDocked", {
		dockingPortId: guestPort.id,
		hostDockingPortId: hostPort.id,
		hostShipId: host!.id,
		jointId: jointEntity.id,
	});
	hostPort.updateComponent("isDockingPort", { connectedPortId: guestPort.id });
	guestPort.updateComponent("isDockingPort", { connectedPortId: hostPort.id });
}

export function undock(guest: Entity) {
	if (!guest.components.isDocked) return;
	const { dockingPortId, hostDockingPortId, jointId } = guest.components.isDocked;

	const hostDockingPort = guest.ecs.getEntityById(hostDockingPortId);
	const guestDockingPort = guest.ecs.getEntityById(dockingPortId);
	guest.ecs.removeEntityById(jointId || -1);
	guest.removeComponent("isDocked");
	hostDockingPort?.updateComponent("isDockingPort", { connectedPortId: null });
	guestDockingPort?.updateComponent("isDockingPort", { connectedPortId: null });
}
